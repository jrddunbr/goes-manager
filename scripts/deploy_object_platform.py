#!/usr/bin/env python3
"""Deploy the object platform with rootless Podman and import existing SatDump data."""
from __future__ import annotations

import argparse
import fcntl
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys
import time

REPO = Path(__file__).resolve().parents[1]
COMPOSE = REPO / "compose.object-platform.yml"
CORE = ["rustfs", "couchdb", "rabbitmq"]
WORKERS = ["ingest-watcher", "ingest-uploader", "decoder-worker", "materializer-worker",
           "catalog-api", "dashboard-api", "goes-dashboard", "reconciler", "backfill-runner"]
IMAGES = {
    "RUSTFS_IMAGE": "docker.io/rustfs/rustfs:1.0.5",
    "COUCHDB_IMAGE": "docker.io/library/couchdb:3.5.0",
    "RABBITMQ_IMAGE": "docker.io/library/rabbitmq:4.2.0-management",
    "PYTHON_IMAGE": "docker.io/library/python:3.14-slim",
}


def run(command, *, capture=False, env=None):
    result = subprocess.run(command, cwd=REPO, env=env, check=True, text=True,
                            stdout=subprocess.PIPE if capture else None)
    return result.stdout.strip() if capture else ""


def load_env(path):
    values = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            key, value = line.split("=", 1)
            # Generated files use literal single-quoted dotenv values, never shell evaluation.
            if value.startswith("'") and value.endswith("'"):
                value = value[1:-1]
            values[key] = value
    return values


def save_env(path, values):
    for key, value in values.items():
        if any(c in str(value) for c in "\n\r'\0"):
            raise ValueError(f"Unsupported characters in {key}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(".tmp")
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write("# Generated by deploy_object_platform.py; contains credentials.\n")
        for key, value in values.items():
            handle.write(f"{key}='{value}'\n")
    temporary.chmod(0o600)
    temporary.replace(path)


def wait_healthy(compose, names, env, timeout):
    deadline = time.monotonic() + timeout
    pending = set(names)
    while pending:
        for service in list(pending):
            ids = run([*compose, "ps", "-q", service], capture=True, env=env).splitlines()
            if not ids:
                continue
            states = json.loads(run(["podman", "inspect", *ids], capture=True, env=env))
            if all((s["State"].get("Health") or s["State"].get("Healthcheck", {})).get("Status") == "healthy" for s in states):
                pending.remove(service)
        if not pending:
            return
        if time.monotonic() >= deadline:
            raise RuntimeError("Services did not become healthy: " + ", ".join(sorted(pending)))
        time.sleep(3)


def tree_size(root):
    total = 0
    count = 0
    for directory, dirs, files in os.walk(root, followlinks=False):
        dirs[:] = [d for d in dirs if not (Path(directory) / d).is_symlink()]
        for name in files:
            path = Path(directory) / name
            if not path.is_symlink() and path.is_file():
                total += path.stat().st_size
                count += 1
    return count, total


def systemd_unit(compose, env_file, source, data):
    # systemd syntax is separate from shell quoting; escape specifiers and quotes.
    def quote(value):
        return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"').replace('%', '%%') + '"'
    executable = shutil.which("podman-compose") or "/usr/bin/podman-compose"
    base = [executable, "--in-pod", "false", "--profile", "tools", "--profile", "retention", "--env-file", env_file, "-p", "goes-object-platform", "-f", COMPOSE]
    return f'''[Unit]
Description=GOES object platform (Podman)
Wants=network-online.target
After=network-online.target
RequiresMountsFor={quote(source)} {quote(data)}

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory={quote(REPO)}
ExecStart={" ".join(quote(v) for v in [*base, "up", "-d", *CORE, *WORKERS])}
ExecStop={" ".join(quote(v) for v in [*base, "stop"])}
TimeoutStartSec=600
TimeoutStopSec=180

[Install]
WantedBy=default.target
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="Root of existing data; mounted read-only")
    parser.add_argument("--data-dir", type=Path, required=True, help="Dedicated platform directory on mounted SSD")
    parser.add_argument("--env-file", type=Path, default=REPO / ".env.object-platform")
    parser.add_argument("--plan", action="store_true", help="Read-only preflight; no Podman or filesystem changes")
    parser.add_argument("--skip-migration", action="store_true", help="Start live ingest without a verified archive import")
    parser.add_argument("--enable-retention", action="store_true", help="Enable object deletion after successful import")
    parser.add_argument("--dashboard-bind", default="127.0.0.1", help="Use 0.0.0.0 for LAN dashboard access")
    parser.add_argument("--ssd-mount", type=Path, help="SSD mount point; defaults to data-dir parent")
    parser.add_argument("--timeout", type=int, default=600)
    args = parser.parse_args(argv)
    source, data, env_file = args.source.resolve(), args.data_dir.resolve(), args.env_file.resolve()
    if not source.is_dir():
        parser.error(f"Source directory does not exist: {source}")
    if source == Path('/') or source == REPO or REPO.is_relative_to(source):
        parser.error("Choose a data-only source tree, not the repository or its parent")
    if data == source or data.is_relative_to(source) or source.is_relative_to(data):
        parser.error("Source and platform data directories must be separate, non-nested trees")
    if not data.parent.is_dir():
        parser.error("The SSD parent directory must already exist and be mounted")
    mount = (args.ssd_mount or data.parent).resolve()
    if not data.is_relative_to(mount):
        parser.error("data-dir must be inside the SSD mount")
    if not args.plan and not mount.is_mount():
        parser.error(f"SSD is not mounted at {mount}; refusing to write platform data elsewhere")
    count, size = tree_size(source)
    free = shutil.disk_usage(data if data.exists() else data.parent).free
    required = int(size * 1.15) + 1024 ** 3
    print(f"Source: {source} ({count:,} regular files, {size / 1024**3:.2f} GiB)", flush=True)
    print(f"Platform SSD directory: {data}; free: {free / 1024**3:.2f} GiB", flush=True)
    print("Import retains originals and verifies every object by reading back its SHA-256.", flush=True)
    if args.plan:
        print(f"Conservative initial free-space requirement: {required / 1024**3:.2f} GiB")
        print("Plan only: no files changed or containers started.")
        return 0
    if not count:
        parser.error("Source tree is empty; use the actual SatDump data directory")
    existing = load_env(env_file)
    for key, value in [("OBJECT_PLATFORM_SOURCE_DIR", source), ("OBJECT_PLATFORM_DATA_DIR", data)]:
        if key in existing and Path(existing[key]).resolve() != value:
            parser.error(f"{key} differs from existing deployment; use its original paths")
    if not existing and free < required:
        parser.error("Not enough free SSD space for an initial import plus headroom")
    if not shutil.which("podman") or not shutil.which("podman-compose"):
        parser.error("Install podman and podman-compose first (64-bit Raspberry Pi OS)")
    os.umask(0o077)
    data.mkdir(exist_ok=True)
    lock = (data / "deploy.lock").open("w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        parser.error("Another deployment or migration is using this SSD directory")
    for name in ["rustfs", "rustfs-logs", "couchdb", "rabbitmq", "migration", "testdata"]:
        (data / name).mkdir(exist_ok=True)
    values = {**IMAGES, **existing}
    values.update(OBJECT_PLATFORM_SOURCE_DIR=str(source), OBJECT_PLATFORM_DATA_DIR=str(data),
                  OBJECT_PLATFORM_DASHBOARD_BIND=args.dashboard_bind,
                  OBJECT_PLATFORM_RETENTION_ENABLED="false")
    for key in ["COUCHDB_PASSWORD", "RABBITMQ_PASSWORD", "RUSTFS_ACCESS_KEY", "RUSTFS_SECRET_KEY"]:
        if not values.get(key):
            values[key] = secrets.token_hex(24)
    values.setdefault("COUCHDB_USER", "goes")
    values.setdefault("RABBITMQ_USER", "goes")
    # Credentials are interpolated in URLs: generated hex is safe; reject unsafe manual edits.
    for key in ["COUCHDB_USER", "COUCHDB_PASSWORD", "RABBITMQ_USER", "RABBITMQ_PASSWORD"]:
        if any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._~" for c in values[key]):
            parser.error(f"{key} must use URL-safe characters")
    save_env(env_file, values)
    env = dict(os.environ)
    # Do not let stale shell exports silently override this deployment's saved settings.
    env.update(values)
    compose = ["podman-compose", "--in-pod", "false", "--profile", "tools", "--profile", "retention", "--env-file", str(env_file), "-p", "goes-object-platform", "-f", str(COMPOSE)]
    run([*compose, "config"], capture=True, env=env)
    run(["podman", "info", "--format", "{{.Host.Arch}}"], env=env)
    # Resolve moving base tags once and persist exact registry digests for later deployments.
    for key in IMAGES:
        run(["podman", "pull", values[key]], env=env)
        images = json.loads(run(["podman", "image", "inspect", values[key]], capture=True, env=env))
        digests = images[0].get("RepoDigests", [])
        if not digests:
            raise RuntimeError(f"No registry digest for {key}")
        values[key] = digests[0]
    save_env(env_file, values)
    env.update(values)
    run(["podman", "build", "--build-arg", f"PYTHON_IMAGE={values['PYTHON_IMAGE']}",
         "-f", "containers/object-platform/Containerfile", "-t", "localhost/goes-object-platform:0.1.0", "."], env=env)
    # Stop consumers/controllers while the importer operates synchronously; preserve queued jobs.
    run([*compose, "stop", *WORKERS, "retention-controller", "metadata-retention-controller"], env=env)
    run([*compose, "up", "-d", *CORE], env=env)
    wait_healthy(compose, CORE, env, args.timeout)
    run([*compose, "exec", "-T", "rabbitmq", "rabbitmqctl", "set_policy", "goes-bounds", ".*",
         '{"max-length-bytes":268435456,"overflow":"reject-publish"}', "--apply-to", "queues"], env=env)
    run([*compose, "run", "--rm", "platform-init"], env=env)
    if not args.skip_migration:
        run([*compose, "run", "--rm", "migration"], env=env)
    if args.enable_retention:
        values["OBJECT_PLATFORM_RETENTION_ENABLED"] = "true"
        save_env(env_file, values)
        env.update(values)
    enabled = WORKERS + (["retention-controller", "metadata-retention-controller"] if args.enable_retention else [])
    run([*compose, "up", "-d", "--force-recreate", *enabled], env=env)
    wait_healthy(compose, enabled, env, args.timeout)
    unit = systemd_unit(compose, env_file, source, data)
    unit = unit.replace("[Service]", f"ConditionPathIsMountPoint={mount}\n\n[Service]")
    if args.enable_retention:
        # Explicitly include optional controllers in boot startup.
        unit = unit.replace('"backfill-runner"', '"backfill-runner" "retention-controller" "metadata-retention-controller"')
    unit_path = data / "goes-object-platform.service"
    unit_path.write_text(unit)
    print(f"Deployment ready. Migration report: {data / 'migration/latest.json'}")
    print(f"Dashboard: http://{args.dashboard_bind}:18094 ; object API: http://{args.dashboard_bind}:18090/api/summary")
    print(f"Boot unit prepared: {unit_path} (installation steps in deployment docs)")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (subprocess.CalledProcessError, RuntimeError, ValueError, OSError) as exc:
        print(f"Deployment stopped: {exc}", file=sys.stderr)
        print("Source files were retained. Correct the error and rerun the same command.", file=sys.stderr)
        raise SystemExit(1)
